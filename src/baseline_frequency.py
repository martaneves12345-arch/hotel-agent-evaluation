#“Se um hotel manager simplesmente priorizasse os problemas mais frequentes nas reviews, que decisão obteria?”

from __future__ import annotations

from typing import Any


# ==========================================================
# CONFIGURATION
# ==========================================================

DEFAULT_MAX_PRIORITIES = 5


# ==========================================================
# HELPERS
# ==========================================================

def _safe_int(
    value: Any,
    default: int = 0,
) -> int:
    """
    Safely converts a value to integer.
    """

    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def _safe_float(
    value: Any,
    default: float = 0.0,
) -> float:
    """
    Safely converts a value to float.
    """

    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _calculate_negative_share(
    positive_mentions: int,
    negative_mentions: int,
) -> float:
    """
    Calculates the share of negative mentions among
    positive + negative lexical mentions.
    """

    total = (
        positive_mentions
        + negative_mentions
    )

    if total == 0:
        return 0.0

    return round(
        negative_mentions / total,
        4,
    )


# ==========================================================
# FREQUENCY RANKING
# ==========================================================

def _rank_categories_by_frequency(
    managerial_evidence: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """
    Ranks managerial categories using negative review
    mentions only.

    This baseline intentionally ignores:
    - expectation violations;
    - emerging-negative signals;
    - diagnostic_score;
    - business-performance trends;
    - experiential indicators;
    - complaint severity;
    - safety reasoning;
    - recent reversals;
    - LLM reasoning.

    This provides a transparent frequency-based baseline.
    """

    categories = []

    for evidence in managerial_evidence:

        positive_mentions = _safe_int(
            evidence.get(
                "positive_mentions"
            )
        )

        negative_mentions = _safe_int(
            evidence.get(
                "negative_mentions"
            )
        )

        negative_share = (
            _calculate_negative_share(
                positive_mentions,
                negative_mentions,
            )
        )

        categories.append(
            {
                "area": evidence.get(
                    "area"
                ),
                "managerial_domain": evidence.get(
                    "managerial_domain"
                ),
                "positive_mentions": (
                    positive_mentions
                ),
                "negative_mentions": (
                    negative_mentions
                ),
                "negative_share": (
                    negative_share
                ),
            }
        )

    # ------------------------------------------------------
    # PRIMARY RANKING:
    # 1. negative mentions
    # 2. negative share
    # 3. alphabetical area name for deterministic tie-break
    # ------------------------------------------------------

    categories.sort(
        key=lambda row: (
            -row[
                "negative_mentions"
            ],
            -row[
                "negative_share"
            ],
            str(
                row.get(
                    "area",
                    ""
                )
            ).lower(),
        )
    )

    return categories


# ==========================================================
# PRIORITY LABEL
# ==========================================================

def _assign_frequency_priority(
    rank: int,
    negative_mentions: int,
) -> str:
    """
    Simple descriptive priority label.

    The ranking itself remains based purely on frequency.
    """

    if negative_mentions <= 0:
        return "low"

    if rank == 1:
        return "high"

    if rank <= 3:
        return "medium"

    return "low"


# ==========================================================
# BASELINE
# ==========================================================

def run_frequency_baseline(
    agent_context: dict[str, Any],
    max_priorities: int = DEFAULT_MAX_PRIORITIES,
) -> dict[str, Any]:
    """
    Runs a deterministic frequency-based managerial
    prioritization baseline.

    Parameters
    ----------
    agent_context:
        Context generated by build_agent_context().

    max_priorities:
        Maximum number of categories returned.

    Returns
    -------
    dict
        Structured baseline output.
    """

    managerial_evidence = (
        agent_context.get(
            "managerial_evidence",
            []
        )
    )

    ranked_categories = (
        _rank_categories_by_frequency(
            managerial_evidence
        )
    )

    # Ignore categories with no negative evidence.
    ranked_categories = [
        category
        for category
        in ranked_categories
        if category[
            "negative_mentions"
        ] > 0
    ]

    selected = ranked_categories[
        :max_priorities
    ]

    priorities = []

    for rank, category in enumerate(
        selected,
        start=1,
    ):

        negative_mentions = (
            category[
                "negative_mentions"
            ]
        )

        positive_mentions = (
            category[
                "positive_mentions"
            ]
        )

        negative_share = (
            category[
                "negative_share"
            ]
        )

        priorities.append(
            {
                "rank": rank,

                "area": category[
                    "area"
                ],

                "managerial_domain": (
                    category[
                        "managerial_domain"
                    ]
                ),

                "managerial_priority": (
                    _assign_frequency_priority(
                        rank=rank,
                        negative_mentions=(
                            negative_mentions
                        ),
                    )
                ),

                "negative_mentions": (
                    negative_mentions
                ),

                "positive_mentions": (
                    positive_mentions
                ),

                "negative_share": (
                    negative_share
                ),

                "rationale": (
                    f"{category['area']} was ranked "
                    f"#{rank} because it contains "
                    f"{negative_mentions} negative "
                    f"review mentions."
                ),
            }
        )

    return {
        "system": (
            "frequency_baseline"
        ),

        "method": (
            "negative_review_frequency"
        ),

        "case_id": (
            agent_context
            .get(
                "case",
                {}
            )
            .get(
                "case_id"
            )
        ),

        "priorities": priorities,

        "methodological_note": (
            "Categories are ranked using negative "
            "review-mention frequency only. "
            "No LLM reasoning, expectation indicators, "
            "trend information, complaint severity, "
            "safety interpretation, or diagnostic score "
            "is used."
        ),
    }